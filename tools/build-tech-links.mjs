/**
 * Writes js/tech-unlock-links.js (T3402): for every building and district of the planet simulator,
 * the technologies of the current tech tree data file that unlock it (their `unlocks[].sim`).
 * The simulator imports that small file to link its catalogue entries to the tech tree, instead of
 * downloading the whole tech data file.
 *
 * Run from the project root after adding or regenerating a tech data file:
 *   node tools/build-tech-links.mjs          (writes the file)
 *   node tools/build-tech-links.mjs --print  (prints it; the smoke tests compare both)
 */
import { writeFileSync } from "node:fs";
import { currentTechVersion, loadTechData } from "../js/tech-versions.js";

export async function buildTechLinks() {
  const data = await loadTechData(currentTechVersion());
  const links = { buildings: {}, districts: {} };
  data.technologies.forEach((tech) => tech.unlocks.forEach((unlock) => {
    if (!unlock.sim || !links[unlock.sim.collection]) return;
    const list = (links[unlock.sim.collection][unlock.sim.id] ||= []);
    if (!list.some((entry) => entry.id === tech.id)) list.push({ id: tech.id, name: tech.name });
  }));
  const sorted = (map) => Object.fromEntries(Object.keys(map).sort().map((key) => [key, map[key].sort((a, b) => a.id.localeCompare(b.id))]));
  const body = JSON.stringify({ rulesetId: data.rulesetId, buildings: sorted(links.buildings), districts: sorted(links.districts) }, null, 2);
  return "// Generated by tools/build-tech-links.mjs from the current tech tree data file (T3402). Do not edit by hand.\n"
    + "// Simulator building / district id → technologies that unlock it (tech id and English name).\n"
    + `export const TECH_UNLOCK_LINKS = ${body};\n`;
}

const text = await buildTechLinks();
if (process.argv.includes("--print")) process.stdout.write(text);
else writeFileSync(new URL("../js/tech-unlock-links.js", import.meta.url), text);
