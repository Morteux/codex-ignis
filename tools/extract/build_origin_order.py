"""In-game order of the origins for the origins bingo (T2402): python tools/extract/build_origin_order.py [--data DIR] [--out FILE]

--data is a data/generated/<rulesetId>/ folder (default: the newest one) and --out the module
(default: js/bingo-origin-order.js). Reads origins.json (extract_civics.py, T2511) and writes the
game ids of every origin sorted by `game_order` (their definition order in the game files, the
order of the empire creation screen). The module is rewritten as a whole (never edit it by hand).
"""
import argparse, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace("\\", "/")
DEFAULT_OUT = os.path.join(ROOT, "js", "bingo-origin-order.js")


def newest_data_dir():
    base = os.path.join(ROOT, "data", "generated")
    dirs = sorted(d for d in os.listdir(base) if os.path.isfile(os.path.join(base, d, "origins.json")))
    if not dirs:
        raise SystemExit("no data/generated/<rulesetId>/origins.json: run tools/extract/extract_civics.py first")
    return os.path.join(base, dirs[-1])


def build(data_dir):
    with open(os.path.join(data_dir, "origins.json"), encoding="utf-8") as f:
        data = json.load(f)
    items = sorted(data["items"], key=lambda item: item["game_order"])
    ids = [item["id"] for item in items]
    lines = [
        f"// Generated by tools/extract/build_origin_order.py from data/generated/{data['rulesetId']}/origins.json (T2402). Do not edit by hand.",
        "// Game ids of every origin in the in-game order (definition order of common/governments/civics).",
        f"export const ORIGIN_ORDER_VERSION = {json.dumps(data['rulesetId'])};",
        "export const ORIGIN_GAME_ORDER = [",
    ]
    lines += [f"  {json.dumps(origin_id)}," for origin_id in ids]
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", help="data/generated/<rulesetId>/ folder (default: the newest one)")
    parser.add_argument("--out", default=DEFAULT_OUT, help="module to write (default: js/bingo-origin-order.js)")
    args = parser.parse_args()
    text = build(args.data or newest_data_dir())
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
