"""Bingo cells taken from the game data (section 35): python tools/extract/build_bingo_game_items.py [--data DIR] [--out-items FILE] [--out-strings FILE]

--data is a data/generated/<rulesetId>/ folder (default: the newest one). Writes two generated
modules (rewritten as a whole, never edit them by hand):
- --out-items (default js/bingo-game-items.js): the cells of each bingo, with their icon path in
  the StellarisAssets API, i18n key, tags, DLC and frame.
- --out-strings (default js/i18n-bingo-game.js): the official es/en/jp names of those cells, from
  the extractor localisation (T2520); a name missing in a language falls back to the English one.

T3501 (rare and dangerous technologies): every technology of technologies.json whose tech tree
kind (build_tech_data.kind) is "rare" or "dangerous", rare ones first, each kind by area
(physics, society, engineering), tier and English name; framed purple (rare) or red (dangerous).

T3502 (DLC): every DLC of dlc.json installed with the game (the ones with a category and a
dlc/<folder>; the store-only extras such as the soundtrack are not), by category (expansions,
story packs, species packs, cosmetic packs) and in release order (dlc id) inside each one. Icon:
the big DLC icon of interface/dlc_icons.gfx (every gameplay DLC has it; some have no small one),
else the small one, else null (reserved empty slot: the cosmetic packs have none). The game has
no localised DLC names (only Nomads, in English), so every language uses the dlc_info name.
"""
import argparse, json, os, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_tech_data import kind  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))).replace("\\", "/")
DEFAULT_ITEMS = os.path.join(ROOT, "js", "bingo-game-items.js")
DEFAULT_STRINGS = os.path.join(ROOT, "js", "i18n-bingo-game.js")
LANGUAGES = {"es": "spanish", "en": "english", "jp": "japanese"}
AREAS = ["physics", "society", "engineering"]
TECH_KINDS = ["rare", "dangerous"]
DLC_CATEGORIES = ["expansion", "story_pack", "species_pack", "content_pack"]


def newest_data_dir():
    base = os.path.join(ROOT, "data", "generated")
    dirs = sorted(d for d in os.listdir(base) if os.path.isfile(os.path.join(base, d, "technologies.json")))
    if not dirs:
        raise SystemExit("no data/generated/<rulesetId>/technologies.json: run tools/extract/extract_technologies.py first")
    return os.path.join(base, dirs[-1])


def load(data_dir, name):
    with open(os.path.join(data_dir, name + ".json"), encoding="utf-8") as f:
        return json.load(f)


def localised(data_dir, set_name):
    """{lang: {game id: name}} of one localisation set."""
    return {lang: load(os.path.join(data_dir, "localisation"), language)["sets"].get(set_name, {}) for lang, language in LANGUAGES.items()}


def tech_items(data_dir, strings):
    techs = load(data_dir, "technologies")
    names = localised(data_dir, "technologies")
    chosen = [t for t in techs["items"] if kind(t["flags"]) in TECH_KINDS]
    chosen.sort(key=lambda t: (TECH_KINDS.index(kind(t["flags"])), AREAS.index(t["area"]), t["tier"] or 0, t["name"]))
    items = []
    for t in chosen:
        key = "bingoTech_" + t["id"]
        for lang in LANGUAGES:
            strings[lang][key] = names[lang].get(t["id"]) or names["en"].get(t["id"]) or t["name"]
        tech_kind = kind(t["flags"])
        items.append({
            "id": t["id"],
            "img": (t.get("icon") or {}).get("asset"),
            "i18nKey": key,
            "tags": [tech_kind, t["area"]],
            "dlc": (t.get("dlc") or [None])[0],
            "frame": tech_kind,
        })
    return techs["rulesetId"], items


def dlc_items(data_dir, strings):
    dlcs = load(data_dir, "dlc")
    names = localised(data_dir, "dlc")
    chosen = [d for d in dlcs["items"] if d["installed"] and d["category"] in DLC_CATEGORIES]
    chosen.sort(key=lambda d: (DLC_CATEGORIES.index(d["category"]), d["id"]))
    items = []
    for d in chosen:
        key = "bingoDlc_" + d["id"]
        for lang in LANGUAGES:
            strings[lang][key] = names[lang].get(d["id"]) or d["localised_name"] or d["name"]
        icon = d.get("icon_big") or d.get("icon") or {}
        items.append({
            "id": d["id"],
            "img": icon.get("asset"),
            "i18nKey": key,
            "tags": [d["category"]],
            "dlc": d["name"],
        })
    return items


def build(data_dir):
    """(items module text, strings module text)."""
    strings = {lang: {} for lang in LANGUAGES}
    ruleset, techs = tech_items(data_dir, strings)
    dlcs = dlc_items(data_dir, strings)
    source = f"data/generated/{ruleset}/"
    item_lines = [
        f"// Generated by tools/extract/build_bingo_game_items.py from {source} (section 35). Do not edit by hand.",
        "// Cells of the bingos taken from the game data (see js/bingo-data.js for the item format).",
        f"export const BINGO_GAME_VERSION = {json.dumps(ruleset)};",
        "// T3501: rare and dangerous technologies (tech tree kind), rare first.",
        "export const TECH_BINGO = [",
    ]
    item_lines += ["  " + json.dumps(item, ensure_ascii=False, separators=(", ", ": ")) + "," for item in techs]
    item_lines.append("];")
    item_lines += [
        "// T3502: DLCs installed with the game, by category and release order; img null = no icon in the game (reserved slot).",
        "export const DLC_BINGO = [",
    ]
    item_lines += ["  " + json.dumps(item, ensure_ascii=False, separators=(", ", ": ")) + "," for item in dlcs]
    item_lines.append("];")
    string_lines = [
        f"// Generated by tools/extract/build_bingo_game_items.py from {source}localisation/ (section 35). Do not edit by hand.",
        "// Official game names of the cells of js/bingo-game-items.js, es/en/jp.",
        'import { addStrings } from "./i18n.js";',
        "",
        "export const strings = {",
    ]
    for lang in LANGUAGES:
        string_lines.append(f"    {lang}: {{")
        string_lines += [f"        {key}: {json.dumps(value, ensure_ascii=False)}," for key, value in strings[lang].items()]
        string_lines.append("    },")
    string_lines += ["};", "", "addStrings(strings);"]
    return "\n".join(item_lines) + "\n", "\n".join(string_lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--data", help="data/generated/<rulesetId>/ folder (default: the newest one)")
    parser.add_argument("--out-items", default=DEFAULT_ITEMS, help="items module (default: js/bingo-game-items.js)")
    parser.add_argument("--out-strings", default=DEFAULT_STRINGS, help="strings module (default: js/i18n-bingo-game.js)")
    args = parser.parse_args()
    items, strings = build(args.data or newest_data_dir())
    for path, text in ((args.out_items, items), (args.out_strings, strings)):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
