"""Economic categories of common/economic_categories: what each generated modifier applies to (T2518):
python tools/extract/extract_economic_categories.py [--game DIR] [--icons [DIR]]

A modifier generated by a category (`planet_miners_minerals_produces_mult`) applies to every
object (job, building, district...) whose `resources = { category = ... }` is that category or,
for `_mult` modifiers only, one of its descendants (see the game's 99_README_ECONOMIC_CATEGORIES.txt).
"""
from pdx.output import DataSet, main
from pdx.parser import Block
from pdx.text import cond, loc, strings

# Game folders whose objects declare `resources = { category = ... }`
USERS = {
    "jobs": "common/pop_jobs",
    "buildings": "common/buildings",
    "districts": "common/districts",
    "zones": "common/zones",
    "deposits": "common/deposits",
    "edicts": "common/edicts",
    "pop_categories": "common/pop_categories",
}


def used_by(game):
    """{category: {kind: [ids]}} of the objects whose resources declare a category."""
    out = {}
    for kind, folder in USERS.items():
        for _, key, item in game.folder(folder):
            if not isinstance(item, Block):
                continue
            for res_key in ("resources", "overlord_resources", "automation_resources"):
                res = item.get(res_key)
                cat = res.get("category") if isinstance(res, Block) else None
                if cat is not None:
                    ids = out.setdefault(str(cat), {}).setdefault(kind, [])
                    if key not in ids:
                        ids.append(key)
    return out


def merge(dicts):
    """{kind: [ids]} dicts merged in order, without repeated ids."""
    out = {}
    for d in dicts:
        for kind, ids in d.items():
            out.setdefault(kind, []).extend(i for i in ids if i not in out[kind])
    return out


def extract(game):
    users = used_by(game)
    raw = [(file, key, c) for file, key, c in game.folder("common/economic_categories") if isinstance(c, Block)]
    parents = {key: c.get("parent") for _, key, c in raw}
    children = {}
    for key, parent in parents.items():
        if parent:
            children.setdefault(parent, []).append(key)

    def ancestors(key):
        chain, p = [], parents.get(key)
        while p and p not in chain:
            chain.append(p)
            p = parents.get(p)
        return chain

    def descendants(key):
        out = []
        for c in children.get(key, []):
            out += [c] + descendants(c)
        return out

    items, warnings = [], []
    for file, key, c in raw:
        mult, add = strings(c.get("generate_mult_modifiers")), strings(c.get("generate_add_modifiers"))
        desc = descendants(key)
        items.append({
            "id": key,
            "file": file,
            **loc(game, key),
            "parent": parents[key],
            "ancestors": ancestors(key),
            "children": children.get(key, []),
            "hidden": c.get("hidden") is True,
            "modifier_category": c.get("modifier_category"),
            "generate_mult_modifiers": mult,
            "generate_add_modifiers": add,
            # Generated modifier keys; <resource> is any resource (minerals, energy...). A _mult also
            # exists for every resource at once (planet_jobs_produces_mult)
            "modifiers": [f"{key}_{part}_mult" for part in mult] + [f"{key}_<resource>_{part}_mult" for part in mult]
                         + [f"{key}_<resource>_{part}_add" for part in add],
            "triggered_modifiers": {k: cond(c.get(k)) for k in ("triggered_produces_modifier", "triggered_cost_modifier", "triggered_upkeep_modifier") if c.has(k)},
            # Objects of this category; `_mult` modifiers also reach the ones of its descendants
            "used_by": users.get(key, {}),
            "used_by_descendants": merge(users.get(d, {}) for d in desc),
            "icon_job": c.get("icon"),
        })
        if parents[key] and parents[key] not in parents:
            warnings.append(f"{key}: unknown parent {parents[key]}")
    return DataSet("economic_categories", ["common/economic_categories"] + list(USERS.values()), items, warnings)


if __name__ == "__main__":
    main(extract, __doc__)
