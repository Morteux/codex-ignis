        S = 1.072
        check("Wealth Creation: trade 8", approx(base.get("Trade value"), 8 * S), base)
        energy0 = base["Energy"]
        check("consumer goods -2", approx(base.get("Consumer goods"), -2), base)
        check("Wealth Creation: energy -6 + 8 converted", approx(energy0, -6 + 8 * S), base)
